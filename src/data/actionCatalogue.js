/**
 * The action catalogue (docs/action-catalogue.md, reviewed and approved) as
 * data: the single source of truth for the report's recommended actions
 * (docs/ai-report-spec.md, Step 8). actionCatalogue.test.js keeps it
 * identical to the doc: IDs, order, every text field, triggers, references.
 *
 * Entry IDs are stable (step C lets the model choose entries by ID) and carry
 * the ACT- prefix so they never collide with indicator or item IDs. They are
 * never shown. No entry refers to another entry: any subset can match.
 *
 * trigger.when: conditions evaluated by matchActions (src/engine/actions.js);
 * an entry matches when any condition holds for any of its IDs.
 *   indicatorState { ids, states } — the indicator's input state is one of states
 *   lowScore { ids }               — measured, not a programme gap, engine score ≤ LOW_SCORE_MAX
 *   layer0State { ids, states }    — the item's input state is one of states
 *   processFlag { ids }            — measured, and the engine raises an action flag for it
 */

